-- ---------------------------------------------------------------------------
-- View: one row per session with its total item count
-- ---------------------------------------------------------------------------

create or replace view session_overview
with (security_invoker = true) as
select
  s.id,
  s.created_at,
  s.location,
  s.nickname,
  coalesce(sum(i.count), 0)::int as total_items
from sessions s
left join session_items i on i.session_id = s.id
group by s.id;

-- ---------------------------------------------------------------------------
-- RPC: insert a session and its items in one transaction
-- p_items: [{"category_id": "plastic_bottle", "count": 3, "description": "..."}]
-- ---------------------------------------------------------------------------

create or replace function log_session(
  p_location_raw text,
  p_location     text,
  p_nickname     text,
  p_items_raw    text,
  p_items        jsonb
) returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  new_id uuid;
begin
  insert into sessions (location_raw, location, nickname, items_raw)
  values (p_location_raw, p_location, nullif(trim(p_nickname), ''), p_items_raw)
  returning id into new_id;

  insert into session_items (session_id, category_id, count, description)
  select new_id,
         item->>'category_id',
         (item->>'count')::int,
         item->>'description'
  from jsonb_array_elements(p_items) as item;

  return new_id;
end;
$$;

-- ---------------------------------------------------------------------------
-- Row level security
-- Only the backend (secret key = service_role, which bypasses RLS) has access.
-- RLS on with no policies means the publishable key can read or write nothing.
-- ---------------------------------------------------------------------------

alter table categories    enable row level security;
alter table sessions      enable row level security;
alter table session_items enable row level security;
alter table summaries     enable row level security;

revoke execute on function log_session(text, text, text, text, jsonb) from public, anon, authenticated;
grant  execute on function log_session(text, text, text, text, jsonb) to service_role;

revoke all on session_overview from anon, authenticated;
