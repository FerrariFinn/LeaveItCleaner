-- Item categories the AI normalizer maps free text onto.
-- A table (not an enum) so the list can be adjusted after feedback.
create table if not exists categories (
  id          text primary key,
  label       text not null,
  sort_order  int  not null default 0
);

-- One row per logged beach cleanup (= one form submission).
create table if not exists sessions (
  id            uuid primary key default gen_random_uuid(),
  created_at    timestamptz not null default now(),
  location_raw  text not null,           -- what the surfer typed
  location      text not null,           -- AI-normalized beach / spot name
  nickname      text,                    -- optional
  items_raw     text not null            -- original free-text description of the haul
);

-- Normalized items per session.
create table if not exists session_items (
  id           bigint generated always as identity primary key,
  session_id   uuid not null references sessions(id) on delete cascade,
  category_id  text not null references categories(id),
  count        int  not null check (count > 0),
  description  text                       -- e.g. "blue nylon rope"
);

create index if not exists session_items_session_idx on session_items(session_id);
create index if not exists sessions_created_at_idx   on sessions(created_at);

-- Monthly "What we found" summaries generated by the LLM.
create table if not exists summaries (
  id             bigint generated always as identity primary key,
  month          date not null unique,   -- first day of the month; one summary per month
  content        text not null,
  model          text not null,
  session_count  int  not null,
  item_count     int  not null,
  created_at     timestamptz not null default now()
);

